-- Any existing user whose role is not in app_role would otherwise have no
-- permissions at all; register those roles so they are visible and editable.
INSERT INTO app_role (role, label, description)
SELECT DISTINCT u.role, initcap(u.role), 'Discovered from existing user accounts.'
  FROM anpr_app_users u
 WHERE u.role IS NOT NULL AND u.role <> ''
   AND NOT EXISTS (SELECT 1 FROM app_role r WHERE r.role = u.role)
ON CONFLICT (role) DO NOTHING;
